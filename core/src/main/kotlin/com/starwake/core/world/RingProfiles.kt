    )

    /** Decoded profiles, [COUNT] × [STEPS] opacities (0..1). */
    val values: Array<FloatArray> = Array(COUNT) { decode(RAW[it]) }

    /** `ShipVisualAssets.ringProfile`: pairs of digits → value / 99. */
    fun decode(s: String): FloatArray {
        require(s.length == STEPS * 2) { "ring profile of ${s.length} digits" }
        return FloatArray(STEPS) { i -> ((s[2 * i] - '0') * 10 + (s[2 * i + 1] - '0')) / 99f }
    }

    /** The profile slot of a Sol ring by its planet's name ("Saturn", "Jupiter", "Uranus"), or -1. */
    fun forPlanet(name: String): Int = when (name) {
        "Saturn" -> SATURN
        "Jupiter" -> JUPITER
        "Uranus" -> URANUS
        else -> -1
    }

    /**
     * `ShipRingDebris.densityAt` (`:247`) without the density fallback: the opacity at
     * f = radial distance / outer radius, linear between the steps.
     */
    fun densityAt(profile: FloatArray, f: Double): Double {
        val n = profile.size
        val x = f * n + 0.5
        val step = kotlin.math.floor(x).toInt()
        val t = x - step
        val a = profile[(step).coerceIn(1, n) - 1]
        val b = profile[(step + 1).coerceIn(1, n) - 1]
        return a + (b - a) * t
    }

    /** Index (1-based, as in Appendix D) of the first non-zero step of [profile]: the image's inner edge. */
    fun firstNonZeroStep(profile: FloatArray): Int {
        for (i in profile.indices) if (profile[i] > 0f) return i + 1
        return -1
    }
}
