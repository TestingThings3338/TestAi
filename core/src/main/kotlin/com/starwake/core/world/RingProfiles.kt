package com.starwake.core.world

/**
 * The ring opacity profiles, verbatim from `ShipVisualAssets.RingProfiles` and `RingVariants`
 * (03-world.md 2.7, Appendix D): 128 steps from the planet centre (f = 0) to the outer ring edge
 * (f = 1), two digits each (00..99 → value / 99). Value i (1-based) is the opacity at
 * f = (i − 0.5)/128 and values interpolate linearly (`ShipRingDebris.densityAt`). The ring shader
 * samples them as a 128-texel texture, whose texel centres sit exactly there.
 *
 * Slot order is the Lua's: the three Sol rings, then `Rings.Generic` 1..2 and the five 2026-11-04
 * variants appended by name (Var_Ring_1..5).
 */
object RingProfiles {
    const val STEPS = 128

    const val SATURN = 0
    const val JUPITER = 1
    const val URANUS = 2
    const val GENERIC_FIRST = 3
    const val COUNT = 10

